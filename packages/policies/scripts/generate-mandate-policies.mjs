// Generates policies/mandates.cedar (committed and reviewed like any policy); --check fails if the file is out of date.
// Rules (Phase 2 doc 06 §6.3; Phase 3 doc 02): a person acts on their own records; an agent acts on the principal's
// records only under an active mandate, within its scopes and the record's domain; "manage" covers "submit", which
// covers "read"; identity and mandates are never delegated.
import { readFileSync, writeFileSync } from 'node:fs';

const DOMAINS = ['cases', 'documents', 'appointments', 'payments', 'benefits'];
const LEVELS = ['read', 'submit', 'manage'];
const covering = (level) => LEVELS.slice(LEVELS.indexOf(level));
const q = (s) => `"${s}"`;

let out = `// GENERATED by scripts/generate-mandate-policies.mjs: do not edit by hand. Mandate rules (Phase 3, P3-F5, F6, T4).\n`;
for (const d of DOMAINS) {
  out += `
// ${d}: own records, never while acting for someone else.
@id("M1-own-${d}")
permit (principal is Person, action in [${LEVELS.map((l) => `Action::${q(`${d}:${l}`)}`).join(', ')}], resource is PersonalRecord)
when { resource.owner == principal && resource.domain == ${q(d)} && !(context has actingUnder) };
`;
  for (const l of LEVELS) {
    out += `
// ${d}:${l} for the principal, by the agent of an active mandate whose scopes cover it (${covering(l).map((c) => `${d}:${c}`).join(' or ')}).
@id("M2-mandate-${d}-${l}")
permit (principal is Person, action == Action::${q(`${d}:${l}`)}, resource is PersonalRecord)
when {
  context has actingUnder &&
  context.actingUnder.agent == principal &&
  context.actingUnder.active &&
  context.actingUnder.principal == resource.owner &&
  resource.domain == ${q(d)} &&
  context.actingUnder.scopes.containsAny([${covering(l).map((c) => q(`${d}:${c}`)).join(', ')}])
};
`;
  }
}
out += `
// Identity and mandates: the person themself only.
@id("M1-own-identity-and-mandates")
permit (principal is Person, action in [Action::"identity:manage", Action::"mandates:manage"], resource is PersonalRecord)
when { resource.owner == principal && ["identity", "mandates"].contains(resource.domain) && !(context has actingUnder) };

// F3: identity and mandates can never be delegated, whatever another policy says.
@id("F3-never-delegated")
forbid (principal, action in [Action::"identity:manage", Action::"mandates:manage"], resource)
when { context has actingUnder };
`;

const file = new URL('../policies/mandates.cedar', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== out) { console.error('policies/mandates.cedar is out of date: run node scripts/generate-mandate-policies.mjs'); process.exit(1); }
  console.log('policies/mandates.cedar is up to date');
} else {
  writeFileSync(file, out);
  console.log('wrote policies/mandates.cedar');
}
