#!/usr/bin/env bash
# Staging-shaped rehearsal (O-AC1, O-T3) for everything that does not need a hosting provider, timed end to end:
#   database tier  — 2 or 3 database servers + backup node on systemd containers, built by the postgresql_ha role
#                    (Patroni, etcd, pgBackRest, TLS everywhere, least-privilege accounts);
#   application    — single-node k3s (air-gapped for the application image) on the same network: pg-router and
#                    civora-core from their Helm charts, restricted Pod Security, NetworkPolicy enforced,
#                    migrations as the owner, runtime as the NOBYPASSRLS account, verify-full TLS via pg-router;
#   resilience     — the database leader is frozen; the application is watched from inside the cluster until it
#                    reports the database up again, and its pods must not restart.
# Not covered (provider not selected, Phase 1 E-07): VMs, OS hardening on real hosts, RKE2 (k3s stands in), DNS and
# public TLS, ingress (open question in ADR-013), OpenBao HA, observability stack, second backup site.
#
# Needs: docker (privileged containers; nested containers must work — GitHub runners, not this sandbox), helm,
#        Ansible (ANSIBLE_PLAYBOOK), the civora-core:dev image. Synthetic data only.
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
db_nodes="${DB_NODES:-2}"
k3s_name=civora-k3s-staging
k3s_image=rancher/k3s:v1.33.4-k3s1
k3s_ip=172.31.240.40
port=16444
ns=civora-tn
work="$(mktemp -d)"
start=$(date +%s)
stamp() { echo "[$(( $(date +%s) - start ))s] $*"; }
cleanup() {
  if [[ "${KEEP:-0}" != "1" ]]; then
    docker rm -f "$k3s_name" >/dev/null 2>&1 || true
    for c in $(docker ps -aq --filter network=civora-pgha-test); do docker rm -f "$c" >/dev/null 2>&1 || true; done
    docker network rm civora-pgha-test >/dev/null 2>&1 || true
  fi
  rm -rf "$work"
}
trap cleanup EXIT

# 1. Database tier (role applied from nothing; containers kept; CA and account passwords exported for step 3)
KEEP=1 SETUP_ONLY=1 APP_PATH=0 DB_NODES="$db_nodes" EXPORT_DIR="$work/db" \
  "$root/infra/ansible/tests/postgresql-ha/run.sh" | sed 's/^/  db | /'
# shellcheck disable=SC1091
source "$work/db/env"   # MIGRATOR_PW, APP_PW, DB_SERVERS ("name=ip ...")
stamp "database tier ready ($db_nodes database servers + backup node)"

# 2. k3s on the database network. Application image imported (air-gapped); HAProxy is pulled by digest.
system_images=(rancher/mirrored-pause:3.6 rancher/mirrored-coredns-coredns:1.12.3 rancher/local-path-provisioner:v0.0.31 rancher/mirrored-library-busybox:1.36.1)
for i in "${system_images[@]}" postgres:16-alpine "$k3s_image"; do docker image inspect "$i" >/dev/null 2>&1 || docker pull -q "$i" >/dev/null; done
docker save "${system_images[@]}" civora-core:dev postgres:16-alpine -o "$work/images.tar"
docker rm -f "$k3s_name" >/dev/null 2>&1 || true
docker run -d --name "$k3s_name" --privileged --tmpfs /run --tmpfs /var/run --network civora-pgha-test --ip "$k3s_ip" \
  -p "127.0.0.1:$port:6443" -e K3S_KUBECONFIG_MODE=644 -v "$work/images.tar:/var/lib/rancher/k3s/agent/images/civora-images.tar:ro" \
  "$k3s_image" server --disable=traefik --disable=metrics-server --tls-san=127.0.0.1 >/dev/null
kc() { docker exec -i "$k3s_name" kubectl "$@"; }
until kc get --raw /readyz >/dev/null 2>&1; do sleep 2; done
until kc get nodes -o name 2>/dev/null | grep -q node; do sleep 2; done
kc wait --for=condition=Ready node --all --timeout=180s >/dev/null
docker exec "$k3s_name" cat /etc/rancher/k3s/k3s.yaml | sed "s#https://127.0.0.1:6443#https://127.0.0.1:$port#" > "$work/kubeconfig"
export KUBECONFIG="$work/kubeconfig" NO_PROXY="${NO_PROXY:+$NO_PROXY,}127.0.0.1,localhost" no_proxy="${no_proxy:+$no_proxy,}127.0.0.1,localhost"
until docker exec "$k3s_name" ctr -n k8s.io images ls -q 2>/dev/null | grep -q civora-core; do sleep 2; done
stamp "k3s ready, application image imported"

# 3. Namespaces and secrets (generated by the database step for this run; never written to the repository)
kc create namespace "$ns" >/dev/null
kc create namespace civora-smoke >/dev/null
kc label namespace "$ns" pod-security.kubernetes.io/enforce=restricted >/dev/null
url() { echo "postgres://$1:$2@pg-router:5432/civora_core?sslmode=verify-full&sslrootcert=/var/run/secrets/civora-db-ca/ca.crt"; }
docker cp "$work/db/ca.crt" "$k3s_name:/tmp/cell-ca.crt"
kc -n "$ns" create secret generic pg-router-ca --from-file=ca.crt=/tmp/cell-ca.crt >/dev/null
kc -n "$ns" create secret generic civora-core-db-ca --from-file=ca.crt=/tmp/cell-ca.crt >/dev/null
kc -n "$ns" create secret generic civora-core-db --from-literal=DATABASE_URL="$(url civora_core_app "$APP_PW")" >/dev/null
kc -n "$ns" create secret generic civora-core-db-migrate --from-literal=DATABASE_URL="$(url civora_core_migrator "$MIGRATOR_PW")" >/dev/null

# 4. pg-router (database servers and their addresses from the database step)
router_args=(); i=0; cidrs=()
for s in $DB_SERVERS; do
  router_args+=(--set "servers[$i].name=${s%%=*}" --set "servers[$i].address=${s##*=}"); cidrs+=("${s##*=}/32"); i=$((i+1))
done
router_args+=(--set "networkPolicy.databaseCidrs={$(IFS=,; echo "${cidrs[*]}")}")
helm upgrade --install pg-router "$root/infra/helm/pg-router" -n "$ns" "${router_args[@]}" --wait --timeout 5m >/dev/null \
  || { kc -n "$ns" get pods -o wide; kc -n "$ns" describe pods -l app.kubernetes.io/name=pg-router | tail -30; exit 1; }
stamp "pg-router ready (a primary is known)"

# 5. civora-core: migrations as the owner (pre-install hook), runtime as the least-privilege account
helm upgrade --install civora-core "$root/infra/helm/civora-core" -n "$ns" -f "$root/infra/helm/civora-core/values-local.yaml" \
  --set networkPolicy.databasePodSelector.app\\.kubernetes\\.io/name=pg-router \
  --set migrations.databaseSecret.name=civora-core-db-migrate --set databaseTls.caSecretName=civora-core-db-ca \
  --wait --timeout 5m >/dev/null \
  || { kc -n "$ns" get pods -o wide; kc -n "$ns" logs -l app.kubernetes.io/component=migrate --tail=30 || true; exit 1; }
stamp "civora-core deployed (migrations applied)"

# 6. Smoke tests
fail=0
probe() { # namespace path
  kc -n "$1" run "probe-$RANDOM" --rm -i --restart=Never --image=postgres:16-alpine --image-pull-policy=IfNotPresent \
    --overrides='{"spec":{"securityContext":{"runAsNonRoot":true,"runAsUser":70,"seccompProfile":{"type":"RuntimeDefault"}},"containers":[{"name":"p","image":"postgres:16-alpine","imagePullPolicy":"IfNotPresent","command":["wget","-qO-","-T","5","http://civora-core.'"$ns"'.svc'"$2"'"],"securityContext":{"allowPrivilegeEscalation":false,"capabilities":{"drop":["ALL"]}}}]}}' 2>/dev/null
}
check() { if eval "$2" >/dev/null 2>&1; then echo "  ok   $1"; else echo "  FAIL $1"; fail=1; fi; }
leader() { for s in $DB_SERVERS; do curl -s --noproxy '*' --max-time 3 --cacert "$work/db/ca.crt" "https://${s##*=}:8008/cluster" 2>/dev/null \
  | python3 -c 'import json,sys;print(next(m["name"] for m in json.load(sys.stdin)["members"] if m["role"]=="leader"))' 2>/dev/null && return; done; }
psql_leader() { docker exec -u postgres "$(leader)" psql -h /var/run/postgresql -d civora_core -Atc "$1"; }
restarts() { kc -n "$ns" get pods -l app.kubernetes.io/name=civora-core,app.kubernetes.io/component!=migrate -o jsonpath='{range .items[*]}{.status.containerStatuses[0].restartCount}{" "}{end}'; }
echo "Smoke tests:"
check "health: database up through pg-router (verify-full TLS)" "probe civora-smoke /health | grep -q '\"database\":\"up\"'"
check "locales: ar-TN is rtl"                                   "probe civora-smoke /v1/meta/locales | grep -q '\"dir\":\"rtl\"'"
check "network policy blocks other namespaces"                  "! probe default /health"
check "schemas created and owned by the migrator"               "test \"\$(psql_leader \"select count(*) from pg_namespace where nspname in ('iam','config','audit') and pg_get_userbyid(nspowner)='civora_core_migrator'\")\" = 3"
check "2 replicas ready, restricted pod security"               "kc -n $ns get deploy civora-core -o jsonpath='{.status.readyReplicas}' | grep -qx 2 && kc get ns $ns -o jsonpath='{.metadata.labels.pod-security\\.kubernetes\\.io/enforce}' | grep -qx restricted"
check "pg-router: 2 replicas ready"                             "kc -n $ns get deploy pg-router -o jsonpath='{.status.readyReplicas}' | grep -qx 2"
deploy_s=$(( $(date +%s) - start ))

# 7. Leader crash with the application running in Kubernetes
before=$(restarts); L=$(leader)
t0=$(date +%s)
docker pause "$L" >/dev/null
check "after freezing the leader ($L): application reports the database up again" \
  "for i in \$(seq 1 40); do probe civora-smoke /health | grep -q '\"database\":\"up\"' && exit 0; sleep 3; done; exit 1"
recover_s=$(( $(date +%s) - t0 ))
check "no application pod restarted during the failover (restart counts: $before)" "test \"\$(restarts)\" = \"$before\""
docker unpause "$L" >/dev/null

# 8. Upgrade path: the migration hook runs again (idempotent) and the rollout completes
helm upgrade civora-core "$root/infra/helm/civora-core" -n "$ns" -f "$root/infra/helm/civora-core/values-local.yaml" \
  --set networkPolicy.databasePodSelector.app\\.kubernetes\\.io/name=pg-router \
  --set migrations.databaseSecret.name=civora-core-db-migrate --set databaseTls.caSecretName=civora-core-db-ca \
  --set podAnnotations.rehearsal=upgrade --wait --timeout 5m >/dev/null && echo "  ok   upgrade with migration hook" || { echo "  FAIL upgrade"; fail=1; }

stamp "done (fail=$fail)"
echo "Staging-shaped rehearsal: from nothing to smoke tests passing in ${deploy_s} s; application recovered ${recover_s} s after the leader froze"
exit $fail
