export const CATALOGUES: Record<Lang, Catalogue> = { en, fr, ar };

export function translator(lang: Lang): Translator {
  return createTranslator({ [LOCALES[lang]]: CATALOGUES[lang], [LOCALES.en]: CATALOGUES.en }, LOCALES[lang], LOCALES.en);
}

/** "cases: view, payments: submit" in the person's language. */
export function describeScopes(t: Translator, scopes: string[]): string {
  return scopes.map((s) => {
    const [domain, action] = s.split(':');
    return `${t.t(`scope.${action}`)} ${t.t(`scope.${domain}`)}`;
  }).join(t.dir === 'rtl' ? '، ' : ', ');
}
