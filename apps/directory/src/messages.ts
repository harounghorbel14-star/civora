const CATALOGUES: Record<Lang, Messages> = { ar, fr, en };

export interface T {
  (key: string, vars?: Record<string, string | number>): string;
  kind(k: Kind): string;
  category(c: string): string;
}

export function translator(lang: Lang): T {
  const m = CATALOGUES[lang];
  const t = ((key: string, vars: Record<string, string | number> = {}) => {
    const s = m[key] ?? en[key];
    if (s === undefined) throw new Error(`missing message ${key}`);
    return s.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
  }) as T;
  t.kind = (k) => t(`kind.${k}`);
  t.category = (c) => m[`category.${c}`] ?? en[`category.${c}`] ?? c;
  return t;
}

/** Every language has every key (checked by the tests). */
export const MESSAGE_KEYS = Object.keys(en);
export const messagesOf = (lang: Lang): Messages => CATALOGUES[lang];
